// gendot generates a Graphviz dot file from vendors.json, releases.json and
// graph.json.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"maps"
	"os"
	"slices"
	"strings"
)

type Style struct {
	Color       string `json:"color,omitempty"`
	Style       string `json:"style,omitempty"`
	Description string `json:"description,omitempty"`
}

type Vendor struct {
	Name        string `json:"name"`
	Description string `json:"description"`
	State       string `json:"state"`
	Link        string `json:"link"`
	Node        struct {
		Color  string           `json:"color"`
		Style  string           `json:"style"`
		Status map[string]Style `json:"status"`
	} `json:"node"`
}

// nodeStyle returns the node color and style for a release with the given status.
func (v Vendor) nodeStyle(status string) (color, style string) {
	color, style = v.Node.Color, v.Node.Style
	if s, ok := v.Node.Status[status]; ok {
		if s.Color != "" {
			color = s.Color
		}
		if s.Style != "" {
			style = s.Style
		}
	}
	return color, style
}

type Release struct {
	Name        string `json:"name"`
	Vendor      string `json:"vendor"`
	Version     string `json:"version"`
	Status      string `json:"status"`
	ReleaseDate string `json:"release_date"`
	EOLDate     string `json:"eol_date"`
	Link        string `json:"link"`
	Notes       string `json:"notes"`
}

type Link struct {
	From   string `json:"from"`
	To     string `json:"to"`
	Status string `json:"status"`
	Notes  string `json:"notes"`
}

type Graph struct {
	LinkStyles map[string]Style `json:"link_styles"`
	Links      []Link           `json:"links"`
}

func readJSON(path string, v any) {
	data, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(data, v); err != nil {
		log.Fatalf("%s: %v", path, err)
	}
}

// attrs formats a dot attribute list, or returns "" if there are no attributes.
func attrs(color, style string) string {
	var a []string
	if color != "" {
		a = append(a, fmt.Sprintf("color=%q", color))
	}
	if style != "" {
		a = append(a, fmt.Sprintf("style=%q", style))
	}
	if len(a) == 0 {
		return ""
	}
	return " [" + strings.Join(a, ",") + "]"
}

func comment(notes string) string {
	if notes == "" {
		return ""
	}
	return " // " + notes
}

func main() {
	dir := flag.String("dir", ".", "directory containing the json files")
	out := flag.String("o", "mysql-history-graph-generated.dot", "output file")
	flag.Parse()

	var (
		vendors  []Vendor
		releases []Release
		graph    Graph
	)
	readJSON(*dir+"/vendors.json", &vendors)
	readJSON(*dir+"/releases.json", &releases)
	readJSON(*dir+"/graph.json", &graph)

	vendorByName := make(map[string]Vendor, len(vendors))
	for _, v := range vendors {
		vendorByName[v.Name] = v
	}
	releaseVendor := make(map[string]string, len(releases))
	for _, r := range releases {
		if _, ok := vendorByName[r.Vendor]; !ok {
			log.Fatalf("release %q has unknown vendor %q", r.Name, r.Vendor)
		}
		releaseVendor[r.Name] = r.Vendor
	}
	for _, l := range graph.Links {
		for _, n := range []string{l.From, l.To} {
			if _, ok := releaseVendor[n]; !ok {
				log.Fatalf("link %q -> %q has unknown release %q", l.From, l.To, n)
			}
		}
		if _, ok := graph.LinkStyles[l.Status]; !ok {
			log.Fatalf("link %q -> %q has unknown status %q", l.From, l.To, l.Status)
		}
	}

	f, err := os.Create(*out)
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(f)

	fmt.Fprintln(w, "digraph mysql_history_graph {")
	fmt.Fprintln(w, "\t/* Generated by cmd/gendot from vendors.json, releases.json and graph.json. Do not edit.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "\t   Vendor colors:")
	for _, v := range vendors {
		fmt.Fprintf(w, "\t   %-24s %s", v.Name+":", v.Node.Color)
		for _, status := range slices.Sorted(maps.Keys(v.Node.Status)) {
			if s := v.Node.Status[status]; s.Color != "" {
				fmt.Fprintf(w, ", %s=%s", status, s.Color)
			}
		}
		fmt.Fprintln(w)
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "\t   Link styles:")
	for _, status := range slices.Sorted(maps.Keys(graph.LinkStyles)) {
		fmt.Fprintf(w, "\t   %-24s %s\n", status+":", graph.LinkStyles[status].Description)
	}
	fmt.Fprintln(w, "\t*/")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "\tnodesep=0.5;")
	fmt.Fprintln(w, "\tranksep=0.25;")

	for _, v := range vendors {
		fmt.Fprintln(w)
		header := v.Name
		if v.Description != "" {
			header += " - " + v.Description
		}
		fmt.Fprintf(w, "\t/* %s */\n", header)
		for _, r := range releases {
			if r.Vendor != v.Name {
				continue
			}
			color, style := v.nodeStyle(r.Status)
			fmt.Fprintf(w, "\t%q%s;%s\n", r.Name, attrs(color, style), comment(r.Notes))
		}
		// Links are grouped with the vendor of the release they point to.
		for _, l := range graph.Links {
			if releaseVendor[l.To] != v.Name {
				continue
			}
			s := graph.LinkStyles[l.Status]
			fmt.Fprintf(w, "\t%q -> %q%s;%s\n", l.From, l.To, attrs(s.Color, s.Style), comment(l.Notes))
		}
	}
	fmt.Fprintln(w, "}")
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
}
